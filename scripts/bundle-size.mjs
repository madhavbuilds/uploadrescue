// Measures real bundle sizes from the built packages (run `pnpm build` first).
// Writes benchmarks/bundle-size.md. Sizes are minified with esbuild and gzipped.
import { build } from "esbuild";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

const root = fileURLToPath(new URL("..", import.meta.url));
const tmp = join(root, "node_modules/.cache/bundle-size");
const kb = (n) => `${(n / 1024).toFixed(1)} KB`;

async function measure(contents, { external = [], resolveDir = root } = {}) {
  rmSync(tmp, { recursive: true, force: true });
  mkdirSync(tmp, { recursive: true });
  const result = await build({
    stdin: { contents, resolveDir, loader: "ts" },
    bundle: true,
    minify: true,
    format: "esm",
    splitting: true,
    outdir: tmp,
    platform: "browser",
    target: "es2022",
    external,
    metafile: true,
    write: true,
    logLevel: "silent",
  });
  // Initial = the stdin entry plus chunks it imports statically (transitively).
  // Everything else is only fetched through dynamic import().
  const outputs = result.metafile.outputs;
  const entryFile = Object.keys(outputs).find((f) => outputs[f].entryPoint === "<stdin>");
  const initialFiles = new Set();
  const visit = (file) => {
    if (initialFiles.has(file)) return;
    initialFiles.add(file);
    for (const imp of outputs[file].imports)
      if (imp.kind === "import-statement" && !imp.external) visit(imp.path);
  };
  if (entryFile) visit(entryFile);
  let initial = 0;
  let lazy = 0;
  for (const file of Object.keys(outputs)) {
    if (!file.endsWith(".js")) continue;
    const gz = gzipSync(readFileSync(join(root, file))).length;
    if (initialFiles.has(file)) initial += gz;
    else lazy += gz;
  }
  return { initial, lazy };
}

const rows = [];
const packageData = [];
const packages = readdirSync(join(root, "packages")).sort();
for (const dir of packages) {
  const pkg = JSON.parse(readFileSync(join(root, "packages", dir, "package.json"), "utf8"));
  const peers = Object.keys(pkg.peerDependencies ?? {});
  const self = await measure(`export * from "${pkg.name}";`, {
    external: [...peers, ...Object.keys(pkg.dependencies ?? {})],
    resolveDir: join(root, "packages", dir),
  });
  const full = await measure(`export * from "${pkg.name}";`, {
    external: peers,
    resolveDir: join(root, "packages", dir),
  });
  rows.push(
    `| \`${pkg.name}\` | ${kb(self.initial)} | ${kb(full.initial)} | ${full.lazy > 0 ? kb(full.lazy) : "—"} |`,
  );
  packageData.push({
    name: pkg.name,
    ownBytes: self.initial,
    withDepsBytes: full.initial,
    lazyBytes: full.lazy,
  });
}

const scenarios = [
  [
    "React: `<UploadRescue>` (react external)",
    `import { UploadRescue } from "@uploadrescue/react"; console.log(UploadRescue);`,
    ["react", "react-dom"],
    "react",
  ],
  [
    "Vanilla: `createUploadRescue`",
    `import { createUploadRescue } from "@uploadrescue/vanilla"; console.log(createUploadRescue);`,
    [],
    "vanilla",
  ],
  [
    "Core only: `createUploadRescue`",
    `import { createUploadRescue } from "@uploadrescue/core"; console.log(createUploadRescue);`,
    [],
    "core",
  ],
];
const scenarioRows = [];
const scenarioData = [];
for (const [label, code, external, dir] of scenarios) {
  const r = await measure(code, { external, resolveDir: join(root, "packages", dir) });
  scenarioRows.push(`| ${label} | ${kb(r.initial)} | ${r.lazy > 0 ? kb(r.lazy) : "—"} |`);
  scenarioData.push({
    id: dir,
    label: label.replace(/`/g, ""),
    initialBytes: r.initial,
    lazyBytes: r.lazy,
  });
}
rmSync(tmp, { recursive: true, force: true });

const report = `# Bundle size

Generated by \`pnpm size\` on ${new Date().toISOString().slice(0, 10)} from the built packages (esbuild, minified, gzip).
These are measured numbers for this revision, not estimates.

## Typical integrations

| Import | Initial (gzip) | Lazy chunks loaded on first optimization (gzip) |
| --- | --- | --- |
${scenarioRows.join("\n")}

## Per package

| Package | Own code (gzip) | With dependencies (gzip) | Lazy chunks (gzip) |
| --- | --- | --- | --- |
${rows.join("\n")}

Notes:
- "Own code" externalises every dependency; "with dependencies" bundles them (peer dependencies such as React stay external).
- The media engine's FFmpeg core (~30 MB WebAssembly) is not bundled; it is downloaded from your server only when a media file is optimized.
`;
mkdirSync(join(root, "benchmarks"), { recursive: true });
writeFileSync(join(root, "benchmarks/bundle-size.md"), report);
writeFileSync(
  join(root, "benchmarks/bundle-size.json"),
  JSON.stringify(
    { date: new Date().toISOString().slice(0, 10), scenarios: scenarioData, packages: packageData },
    null,
    2,
  ) + "\n",
);
console.log(report);
