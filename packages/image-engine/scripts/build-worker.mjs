// Bundles src/worker-entry.ts into a self-contained IIFE string module.
// The output is committed so tests and type checks work without a build;
// CI verifies it is up to date.
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const result = await build({
  entryPoints: [`${root}src/worker-entry.ts`],
  bundle: true,
  format: "iife",
  target: "es2020",
  minify: true,
  write: false,
  legalComments: "none",
});
const code = result.outputFiles[0].text.trim();
writeFileSync(
  `${root}src/generated/worker-source.ts`,
  `// GENERATED by scripts/build-worker.mjs — do not edit.\n/* eslint-disable */\nexport const WORKER_SOURCE: string = ${JSON.stringify(code)};\n`,
);
console.log(`worker-source.ts written (${code.length} bytes)`);
